// Writes docs/THIRD-PARTY-LICENSES.md: every runtime dependency compiled into or shipped with the
// Windows build (Rust crates for x86_64-pc-windows-msvc, normal edges only, plus npm runtime deps
// bundled into the frontend), with version and declared licence. Build/dev tools are listed apart.
// Usage: node scripts/gen-licenses.mjs   (needs cargo on PATH or in %USERPROFILE%\.cargo\bin)
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';

const cargo = fs.existsSync(path.join(os.homedir(), '.cargo', 'bin', 'cargo.exe')) ? path.join(os.homedir(), '.cargo', 'bin', 'cargo.exe') : 'cargo';
const manifest = 'src-tauri/Cargo.toml';
const run = (args) => execFileSync(cargo, args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });

const meta = JSON.parse(run(['metadata', '--manifest-path', manifest, '--format-version', '1', '--locked', '--offline']));
const byId = new Map(meta.packages.map((p) => [`${p.name} ${p.version}`, p]));
const tree = run(['tree', '--manifest-path', manifest, '--locked', '--offline', '-e', 'normal', '--target', 'x86_64-pc-windows-msvc', '--prefix', 'none', '--format', '{p}']);
const runtime = new Map();
for (const line of tree.split('\n')) {
  const m = line.trim().match(/^(\S+) v(\S+)/);
  if (!m) continue;
  const key = `${m[1]} ${m[2]}`;
  if (m[1] === 'aimlite') continue;
  const p = byId.get(key);
  runtime.set(key, { name: m[1], version: m[2], license: p?.license ?? (p?.license_file ? `see ${p.license_file}` : 'unknown'), repo: p?.repository ?? '' });
}

const lock = JSON.parse(fs.readFileSync('package-lock.json', 'utf8'));
const npmRuntime = [];
const npmDev = [];
for (const [k, v] of Object.entries(lock.packages)) {
  if (!k.startsWith('node_modules/')) continue;
  const name = k.slice('node_modules/'.length).replace(/.*node_modules\//, '');
  const entry = { name, version: v.version, license: v.license ?? 'unknown' };
  (v.dev ? npmDev : npmRuntime).push(entry);
}

const counts = {};
for (const r of runtime.values()) counts[r.license] = (counts[r.license] ?? 0) + 1;
let md = '# Third-party licences\n\nGenerated by `node scripts/gen-licenses.mjs` from `Cargo.lock` / `package-lock.json`. Declared licences as published by each package; this is an inventory, not legal advice.\n\n';
md += `## Shipped in the Windows build\n\n### Rust crates (${runtime.size}, target x86_64-pc-windows-msvc, normal dependencies)\n\nLicence summary: ${Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} × ${n}`).join('; ')}\n\n`;
md += '| Crate | Version | Licence |\n|---|---|---|\n';
for (const r of [...runtime.values()].sort((a, b) => a.name.localeCompare(b.name))) md += `| ${r.name} | ${r.version} | ${r.license.replace(/\|/g, '/')} |\n`;
md += `\nSQLite is compiled in through \`libsqlite3-sys\` (bundled); SQLite itself is in the public domain.\n\n### npm packages bundled into the frontend (${npmRuntime.length})\n\n| Package | Version | Licence |\n|---|---|---|\n`;
for (const r of npmRuntime.sort((a, b) => a.name.localeCompare(b.name))) md += `| ${r.name} | ${r.version} | ${r.license} |\n`;
md += `\n### Not shipped, but used by the app at run time\n\n- Microsoft Edge WebView2 Runtime (system component, Microsoft licence terms). The normal installer downloads it only when missing; the offline installer embeds Microsoft's standalone installer.\n\n## Build and test tools only (${npmDev.length} npm packages, not shipped)\n\n`;
md += npmDev.sort((a, b) => a.name.localeCompare(b.name)).map((r) => `${r.name} ${r.version} (${r.license})`).join(', ') + '\n';
md += '\nThe NSIS installer is built with NSIS (zlib/libpng licence) and `nsis_tauri_utils` (MIT/Apache-2.0), downloaded by the Tauri CLI at build time.\n\n## AimLite\'s own assets\n\nIcon: drawn procedurally by `scripts/gen-icon.mjs`. Sounds: synthesised at run time (`src/audio/synth.ts`). Fonts: the Windows system font stack (none bundled). Mode configurations: parameter values recovered from aim400kg.com\'s public pages, with original names; no aim400kg code, artwork, sounds or text are included.\n';
fs.mkdirSync('docs', { recursive: true });
fs.writeFileSync('docs/THIRD-PARTY-LICENSES.md', md);
console.log(`docs/THIRD-PARTY-LICENSES.md: ${runtime.size} crates, ${npmRuntime.length} runtime npm packages`);
